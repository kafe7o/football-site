"""
Проверка: може ли банката да се удвои за месец с колонките на робота и с какъв дял от банката на колонка (майсторът, 22.10:
„разполагаме с 200 евро... от 1 ноември до 1 декември да ми направиш банката да е по две... да ни казва как да процедираме“).

ПРОТОКОЛ (записан преди пускането):
  1. Входът са САМО измерените назад числа на двете логики, които се записват (чиста проверка, не избор): системата - минават 51% при среден
     коеф. 2.11, ~7 колонки на месец само чет-нед (research/master_v2_system.py, pro_price_backtest.py); надстройката - 4 от 5: четворка минава
     31.1% при коеф. 4.17, в 67% от дните поне една, ~4.2 дни на месец (research/adaptive_columns_backtest.py). Мачът на надстройката се моделира
     с 76% (дава 31.6% на четворка и 63% на ден - между двете измерени). Мачовете се приемат независими; цената - средната (не най-добрият букмейкър).
  2. Планът е ДЯЛ от текущата банка: на колонка на системата и на ден с надстройка (разделен на 5-те четворки). Дялове: 5-50%.
  3. Монте Карло (4000 пътя на дял, фиксирано семе) за периода на собственика; спира се при стигната цел или под 1 €.
     Мери се: шанс целта да се стигне до края; шанс за срив (под 1/5 от началната); медиана накрая.
  4. Същото при ПРЕДИМСТВО НУЛА (мачът минава толкова често, колкото казва цената) - защото CLV назад е 0 и нулата не е изключена.
  5. Шансът за целта само расте с дяла (с цялата банка на една колонка той е най-голям) - затова планът е делът с най-голяма РАЗЛИКА
     „шанс за целта минус шанс за срив“ при измереното назад; до него се казват и двете числа. Нищо не се променя в правилата на избора
     на мачове. Числото се казва на собственика; решението е негово.
Резултат: data/bank_backtest.json ({bank, start, end, target, rows, best}).

Пускане (от pipeline/): python -m research.bank_backtest [банка начало край цел]
"""

import json
import sys

from bets import bank, config


def main(argv=None):
    a = argv if argv is not None else sys.argv[1:]
    cfg = {"bank": float(a[0]), "start": a[1], "end": a[2], "target": float(a[3])} if len(a) == 4 else (bank.load() or {"bank": 200.0, "start": "2026-11-01", "end": "2026-12-01", "target": 400.0})
    out = bank.plans(cfg["bank"], cfg["start"], cfg["end"], cfg["target"])
    out.update(cfg)
    (config.DATA_DIR / "bank_backtest.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"Банка {cfg['bank']:.0f} € -> цел {cfg['target']:.0f} €, {cfg['start']} - {cfg['end']}")
    print("дял   | измерено назад: цел   срив   медиана | предимство нула: цел   срив   медиана")
    for r in out["rows"]:
        z = r["zero"]
        print(f"{r['share']:>4.0%}  | {r['target']:>6.0%} {r['bust']:>6.0%} {r['median']:>8.0f} €   | {z['target']:>6.0%} {z['bust']:>6.0%} {z['median']:>8.0f} €")
    print(f"Планът (най-голяма разлика цел - срив): дял {out['best']:.0%}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
